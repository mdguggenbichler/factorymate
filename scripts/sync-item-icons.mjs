#!/usr/bin/env node
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, "..")

const iconsSrc = path.join(root, "assets", "icons")
const iconsManifest = path.join(root, "assets", "icons.json")
const iconsDest = path.join(root, "frontend", "public", "icons")
const keysDest = path.join(root, "frontend", "lib", "generated", "item-icon-keys.ts")

if (!fs.existsSync(iconsSrc)) {
  console.error(`Icon source directory not found: ${iconsSrc}`)
  process.exit(1)
}

if (!fs.existsSync(iconsManifest)) {
  console.error(`Icon manifest not found: ${iconsManifest}`)
  process.exit(1)
}

if (fs.existsSync(iconsDest)) {
  fs.rmSync(iconsDest, { recursive: true, force: true })
}
fs.mkdirSync(iconsDest, { recursive: true })

let copied = 0
for (const file of fs.readdirSync(iconsSrc)) {
  if (!file.endsWith(".png")) {
    continue
  }
  fs.copyFileSync(path.join(iconsSrc, file), path.join(iconsDest, file))
  copied += 1
}

const manifest = JSON.parse(fs.readFileSync(iconsManifest, "utf8"))
const keys = Object.keys(manifest).sort()

fs.mkdirSync(path.dirname(keysDest), { recursive: true })
const lines = keys.map((key) => `  ${JSON.stringify(key)},`).join("\n")
const content = `// Generated by scripts/sync-item-icons.mjs — do not edit manually.

export const ITEM_ICON_KEYS = new Set<string>([
${lines}
])
`

fs.writeFileSync(keysDest, content)
console.log(
  `Synced ${copied} PNGs and ${keys.length} icon keys to frontend/public/icons/`
)
